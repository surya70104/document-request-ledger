def sample_pdf(title: str) -> bytes:
    """A tiny but valid one-page PDF, so the demo downloads open in any viewer."""
    esc = title.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    stream = (
        f"BT /F1 18 Tf 72 720 Td ({esc}) Tj ET\n"
        "BT /F1 10 Tf 72 690 Td (Demo document generated by seed_demo.py) Tj ET"
    )
    objs = [
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R "
        "/Resources << /Font << /F1 5 0 R >> >> >>",
        f"<< /Length {len(stream)} >>\nstream\n{stream}\nendstream",
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = b"%PDF-1.4\n"
    offsets = []
    for number, body in enumerate(objs, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n{body}\nendobj\n".encode("latin-1")
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return out


def backfill_stored_submissions(session) -> int:
    """For a database from an earlier stage: a request already Submitted / Under review has the
    SUBMITTED event but no stored file. Give it one (no new events - the history is untouched) so
    it can be reviewed in the Audit Review panel."""
    made = 0
    requests = session.execute(select(Request)).scalars().all()
    for req in requests:
        if req.state not in ("Submitted", "Under review") or req.submissions:
            continue
        submitted = next((ev for ev in reversed(req.events) if ev.event_type == E.SUBMITTED), None)
        if submitted is None:
            continue
        name = (submitted.payload or {}).get("filename") or f"{req.ref}_submission.pdf"
        data = sample_pdf(f"{req.document} ({req.ref})")
        digest = services.sha256_hex(data)
        rel = f"{req.id}/{digest[:16]}_{services._safe_name(name)}"
        path = services.UPLOAD_DIR / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        sub = Submission(
            request_id=req.id,
            attempt_number=req.attempt_count,
            received_at=submitted.at,
            channel=submitted.channel or "Manual",
            submitted_by=(submitted.payload or {}).get("submitted_by"),
            outcome="pending",
        )
        sub.files.append(
            SubmissionFile(
                request_id=req.id,
                filename=services._safe_name(name),
                content_hash=digest,
                file_bytes_size=len(data),
                storage_path=rel,
                page_order=1,
                retention_basis="none",
                purge_at=utcnow() + timedelta(days=180),
            )
        )
        session.add(sub)
        made += 1
    session.commit()
    return made


def when(days_ago: int, hour: int, minute: int = 0) -> datetime:
    """A timestamp `days_ago` days before today at hour:minute UTC (never in the future)."""
    now = utcnow()
    ts = (now - timedelta(days=days_ago)).replace(hour=hour, minute=minute, second=0, microsecond=0)
    return min(ts, now)


