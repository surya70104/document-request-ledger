def top_up_board_demo(session, eng) -> int:
    """Add the outstanding requests the board demo needs. Idempotent (skips a document that is
    already in the engagement) and safe on a database from an earlier stage."""
    have = {services._normalise_document(r.document) for r in services.engagement_requests(session, eng.id)}
    made = 0
    for document, description, significance, priority, owner, sent_ago, chases in BOARD_DEMO:
        if services._normalise_document(document) in have:
            continue
        actor = MANAGER if significance == "Material" else SENIOR
        try:
            req = services.create_request(
                session, engagement_id=eng.id, document=document, description=description,
                period_from=eng.period_from, period_to=eng.period_to, significance=significance,
                priority=priority, owner_person=owner, actor=actor, at=when(sent_ago + 1, 15),
            )
        except services.DuplicateRequestError:
            continue
        services.append_event(session, req.id, E.SENT, actor, channel="Email", at=when(sent_ago, 9, 30))
        for days_ago, channel in chases:
            services.record_chase(
                session, req.id, SENIOR, channel,
                template="gentle" if days_ago > 10 else "escalate", at=when(days_ago, 11), notify=False,
            )
        made += 1
    return made


