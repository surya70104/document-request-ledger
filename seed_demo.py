def seed_prior_year(session) -> bool:
    """A closed FY 2024-25 engagement for the same client, built from the same template. Some items
    were accepted (one after a rejection and four chases), one waived, two left unfulfilled."""
    if session.execute(select(Engagement).where(Engagement.name == PRIOR_NAME)).scalar_one_or_none():
        return False
    tmpl = services.get_template(session, "Statutory audit")
    items = {it.document: it for it in tmpl.items}
    prior = Engagement(
        name=PRIOR_NAME,
        client_name="Acme Tech Solutions Pvt Ltd",
        engagement_type="Statutory audit",
        period_from=date(2024, 4, 1),
        period_to=date(2025, 3, 31),
        status="Active",
        entity_profile=services.normalise_profile(PRIOR_PROFILE),
        created_at=when(345, 9),
    )
    session.add(prior)
    session.commit()

    for document, owner, sent_ago, chases, outcome in PRIOR_DEMO:
        item = items.get(document)
        if item is None:  # the template was edited; skip rather than guess
            continue
        doc = services._fill(item.document, prior)
        pf, pt = services._item_period(item, prior)
        req = services.create_request(
            session, engagement_id=prior.id, document=doc, owner_person=owner, actor=MANAGER,
            significance=item.significance_default, priority=item.priority_default,
            description=services._fill(item.label_text or item.description, prior),
            period_from=pf, period_to=pt, template_item=f"{tmpl.engagement_type} v{tmpl.version} · #{item.position}",
            template_item_id=item.id, channel="Template", at=when(sent_ago + 1, 15),
        )
        services.append_event(session, req.id, E.SENT, MANAGER, channel="Email", at=when(sent_ago, 9, 30))
        for days_ago, channel in chases:
            services.record_chase(
                session, req.id, SENIOR, channel, template="gentle", at=when(days_ago, 11), notify=False
            )
        last = min([sent_ago] + [d for d, _ in chases])

        def upload(days_ago, tag):
            return services.record_submission(
                session, req.id, owner, [(f"{tag}.pdf", sample_pdf(f"{doc} - {tag}"))],
                channel="Email", submitted_by=owner.split("(")[0].strip(), at=when(days_ago, 12),
            )

        if outcome == "accept":
            sub = upload(last - 4, "final")
            services.review_submission(session, sub["submission"].id, "accept", SENIOR, at=when(last - 6, 14))
        elif outcome == "reject_accept":
            sub = upload(last - 4, "draft")
            services.review_submission(
                session, sub["submission"].id, "reject", SENIOR, reason_code="INCOMPLETE",
                note="Pages missing - send the complete document.", at=when(last - 6, 14),
            )
            sub = upload(last - 12, "complete")
            services.review_submission(session, sub["submission"].id, "accept", SENIOR, at=when(last - 14, 14))
        elif outcome == "waive":
            services.append_event(
                session, req.id, E.WAIVED, MANAGER,
                payload={"reason": "Client reported no related-party transactions in the year."},
                at=when(last - 3, 10),
            )
        # "open": left outstanding; close-out freezes it as Unfulfilled at report date.

    services.close_engagement(session, prior.id, MANAGER, report_date=date(2025, 7, 31), at=when(250, 10))
    return True


